/**
 * Attest — the CP4 packet (brief §9, amended by A1; D3.57).
 *
 * One page the author can answer in one reply: what WP3 found, what WP4 saw
 * change, the ranked WP5 list, every narrative blank, every judgment only the
 * author can make, the approval slot, and the exact response format. It is
 * generated from the same persisted evidence as FINDINGS.md and approves
 * nothing: CP4 is approved only by the author's reply.
 */
import type { Wp5Result } from "./wp5-findings.ts";

type Rec = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

export interface Cp4Inputs {
  readonly wp5: Wp5Result;
  /** The official run's validation (validate-wp3). */
  readonly validation: Rec;
  /** Earlier official runs and why they are not the result. */
  readonly superseded: readonly { readonly runId: string; readonly why: string }[];
  /** Earlier WP4 runs and why they are not the result. */
  readonly supersededWp4: readonly { readonly runId: string; readonly why: string }[];
  readonly drift: Rec | null;
  readonly generatedAt: string;
}

export function renderCp4Packet(x: Cp4Inputs): string {
  const L: string[] = [];
  const p = (s = "") => L.push(s);
  const v = x.validation;
  const t = v.totals as Rec;
  p("# CP4 — findings, risk prioritisation and remediation guidance");
  p();
  p("> **STOP. This is checkpoint CP4** (brief §9, as amended by Amendment A1). Work does not continue past it until the author");
  p("> answers. Nothing in this packet approves anything; CP4 is approved only by the author's own reply. Generated by");
  p(`> \`npm run attest wp5\` at ${x.generatedAt} from persisted evidence; regenerate rather than edit.`);
  p();
  p("Arc21 is a read-only assessment target: no finding was remediated, none is closed, and no remediation was implemented or");
  p("independently verified. The findings narrative is the author's; every blank below is for the author's own words.");
  p();

  // --- 1. WP3 ---------------------------------------------------------------
  p("## 1. WP3 — the assessment");
  p();
  p(`Official run \`${v.runId}\`: **${t.records} Test IDs**, independent validation **${v.passed ? "PASSED" : "FAILED"}** (${(v.checks as Rec[]).filter((c) => c.passed).length} of ${(v.checks as Rec[]).length} checks). Arc21 unchanged before and after.`);
  p();
  p("| Verdict | Test IDs | Meaning |");
  p("|---|---:|---|");
  const meaning: Record<string, string> = {
    effective: "the control held as the approved row predicted",
    deficient: "the control was exercised and did not hold",
    gap: "a control the plan asked about does not exist (audit trail)",
    characterized: "a recorded fact, not a pass or fail",
    not_measured: "a registered contradiction you chose to keep unmeasured",
  };
  for (const [k, n] of Object.entries(t.byVerdict as Record<string, number>)) p(`| ${k} | ${n} | ${meaning[k] ?? ""} |`);
  p();
  const fams = t.byFamily as Record<string, Record<string, number>>;
  const cols = ["effective", "deficient", "gap", "characterized", "not_measured"];
  p(`| Family | ${cols.join(" | ")} |`);
  p(`|---|${cols.map(() => "---:").join("|")}|`);
  const famKey = (f: string) => (/^F(\d+)/.exec(f) ? Number(/^F(\d+)/.exec(f)![1]) : 99);
  for (const [f, row] of Object.entries(fams).sort((a, b) => famKey(a[0]) - famKey(b[0]))) p(`| ${f} | ${cols.map((c) => row[c] ?? 0).join(" | ")} |`);
  p();
  if (x.superseded.length) {
    p("Earlier official runs, kept unedited in `evidence/runs/` and **not** the result:");
    p();
    for (const s of x.superseded) p(`- \`${s.runId}\` — ${s.why}`);
    p();
  }

  // --- 2. WP4 ---------------------------------------------------------------
  p("## 2. WP4 — drift across schema states");
  p();
  if (!x.drift) {
    p("*No WP4 run was supplied.*");
  } else {
    const d = x.drift;
    p(`WP4 run \`${d.runId}\` (report: \`evidence/runs/${d.runId}/wp4/drift-report.md\`).`);
    p();
    p("| State | Source | Migrations | Run |");
    p("|---|---|---:|---|");
    for (const s of d.states as Rec[]) p(`| \`${s.name}\` | ${s.source} | ${s.migrationCount} | ${s.exit === 0 ? "ok" : `exit ${s.exit}`} |`);
    p();
    p("| Compared | controls added | removed | definition changed | attributes changed | new resources (no control) | newly exposed | pass → fail | fail → pass |");
    p("|---|---:|---:|---:|---:|---|---:|---:|---:|");
    for (const df of d.diffs as Rec[]) {
      const c = df.inventory.counts as Rec;
      const rc = (df.results?.counts ?? {}) as Rec;
      p(`| ${df.from} → ${df.to} | ${c.added} | ${c.removed} | ${c.definitionChanged} | ${c.attributesChanged} | ${c.newResources} (${c.newUnprotectedResources}) | ${c.newlyExposed} | ${df.results ? rc["pass → fail"] ?? 0 : "—"} | ${df.results ? rc["fail → pass"] ?? 0 : "—"} |`);
    }
    p();
    for (const df of d.diffs as Rec[]) {
      const tr = (df.results?.transitions ?? []) as Rec[];
      const pf = tr.filter((t) => t.kind === "pass → fail"), fp = tr.filter((t) => t.kind === "fail → pass");
      if (!pf.length && !fp.length) continue;
      const codeOnly = (t: Rec) => /^error /.test(String(t.from?.summary ?? "")) && /^error /.test(String(t.to?.summary ?? ""));
      const show = (xs: Rec[]) => xs.slice(0, 10).map((t) => `\`${t.testId}\` (${t.from?.summary ?? "?"} → ${t.to?.summary ?? "?"}${codeOnly(t) ? ": refused in both states; only where and how it is signalled changed" : ""})`).join(", ") + (xs.length > 10 ? `, … ${xs.length - 10} more` : "");
      p(`- **${df.from} → ${df.to}**${fp.length ? ` — fail → pass: ${show(fp)}` : ""}${pf.length ? `${fp.length ? ";" : " —"} pass → fail: ${show(pf)}` : ""}`);
    }
    for (const df of d.diffs as Rec[]) {
      for (const r of (df.inventory.newResources ?? []) as Rec[]) {
        if (r.unprotected) p(`- **${df.from} → ${df.to}** — new resource with no row-level control: \`${r.resource}\` (${r.clientReachable ? "reachable by a client role now" : "no client grant today — one GRANT from exposed"})`);
      }
    }
    p();
    if (x.supersededWp4.length) {
      p("Earlier WP4 runs, kept unedited and **not** the result:");
      p();
      for (const r of x.supersededWp4) p(`- \`${r.runId}\` — ${r.why}`);
      p();
    }
    p("Historical results are today's approved questions asked of an earlier schema, not findings about Arc21 today. The last");
    p("state adds one Attest-only table with no row-level security to a scratch copy of the current schema — never to Arc21 —");
    p("to show the detector reporting a new unprotected resource without anyone looking for it.");
  }
  p();

  // --- 3. WP5 ---------------------------------------------------------------
  p("## 3. WP5 — the ranked list (full detail in `FINDINGS.md`)");
  p();
  p("| # | Item | Tier | Evidence | Test IDs |");
  p("|---|---|---|---|---:|");
  for (const i of x.wp5.items) p(`| ${i.id} | ${i.title} | ${i.tier} | ${i.evidenceClass === "none" ? "WP0" : i.evidenceClass} | ${i.testIds.length} |`);
  p();
  p("Ranking rule (D3.57): part, then the frozen WP2 tier of the resource at risk, then evidence class, then the most exposed");
  p("path in the frozen rating. Titles, explanations and remediation options are AI-drafted for your review.");
  p();

  // --- 4. narratives --------------------------------------------------------
  const needNarrative = x.wp5.items.filter((i) => i.part !== "limitation");
  p("## 4. What only you can write — the findings narrative");
  p();
  p("For each item: in your own words, what the finding means for Arc21 and its players. It is not drafted for you, and a");
  p("sentence you did not write will not be recorded as yours. Blank until you answer:");
  p();
  for (const i of needNarrative) p(`- **${i.id}** ${i.title} — AUTHOR NARRATIVE: ${i.author.narrative ? "*(recorded)*" : "______"}`);
  p();

  // --- 5. judgments ---------------------------------------------------------
  p("## 5. The judgments only you can make");
  p();
  let n = 0;
  const js: string[] = [];
  for (const i of needNarrative) {
    p(`**${i.id}. ${i.title}** — status: open, or accepted / design intent${i.part === "informational" ? ", or informational" : ""}?`);
    for (const j of i.spec.judgment) { n++; js.push(`J${n}`); p(`- **J${n}** (${i.id}) ${j}`); }
    p();
  }
  n++; const jRank = `J${n}`; js.push(jRank);
  p(`- **${jRank}** The ranking rule (D3.57): accept it, or state the rule you want. A different rule is recorded as your decision; it never changes a frozen tier.`);
  n++; const jRuns = `J${n}`; js.push(jRuns);
  p(`- **${jRuns}** The run record: the earlier WP3 and WP4 runs above are kept as superseded, aborted or stopped records; \`${v.runId}\` is the WP3 result${x.drift ? ` and \`${x.drift.runId}\` the WP4 result` : ""}. Accept?`);
  p();

  // --- 6. approval ----------------------------------------------------------
  p("## 6. CP4 approval");
  p();
  p("**CP4: ______** (approved / not approved — and if not, what must change)");
  p();
  p("Approval here means: the ranked findings, the remediation guidance and the verification procedures are presented and");
  p("understood, the narrative is yours, and WP6 (framework mapping, a study exercise) may begin. It does not mean anything was");
  p("fixed, closed or validated.");
  p();

  // --- 7. response format ---------------------------------------------------
  p("## 7. How to answer — one reply, this format");
  p();
  p("```text");
  p("CP4 RESPONSE");
  for (const i of needNarrative) p(`${i.id} status: open | accepted_design_intent${i.part === "informational" ? " | informational" : ""}`);
  for (const i of needNarrative) p(`${i.id} narrative: <your own words>`);
  for (const j of js) p(`${j}: <your answer>`);
  p("CP4: approved | not approved — <what must change>");
  p("```");
  p();
  p("A line you leave out stays open and blank; nothing is filled in on your behalf. Your words are recorded verbatim in");
  p("`rubric/wp5-author-narratives.json` with the date of your reply, and FINDINGS.md is regenerated from them.");
  p();
  return L.join("\n") + "\n";
}
