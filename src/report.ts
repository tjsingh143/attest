/**
 * Attest — rendering the inventory for a human.
 *
 * The test of this file is in the brief: someone who has never seen Arc21 must
 * be able to read the output and know what the access control surface is. So
 * every table here carries the catalog fact, and where the author wrote a
 * COMMENT, the declared intent sits beside it clearly labelled as a claim
 * rather than a measurement.
 */
import type { Inventory, Observation } from "./inventory.ts";
import type { SchemaVersion } from "./schema-version.ts";
import type { SessionIdentity } from "./db.ts";

export interface RunMeta {
  readonly runId: string;
  readonly startedAt: string;
  readonly schemaVersion: SchemaVersion;
  readonly readAs: SessionIdentity;
  readonly instance: string;
}

const yn = (v: boolean) => (v ? "yes" : "no");
const cell = (v: unknown) => String(v ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
const code = (v: unknown) => (v === null || v === undefined || v === "" ? "—" : "`" + cell(v) + "`");

const OBSERVATION_HEADINGS: Record<Observation["kind"], string> = {
  rls_disabled_and_reachable:
    "Row-level security off, and a client-reachable role holds a privilege",
  rls_disabled_not_reachable:
    "Row-level security off, but no client-reachable role holds a privilege",
  deny_by_default:
    "Row-level security on with no policy, and no client-reachable grant (denies everything)",
  grant_without_policy:
    "Row-level security on with no policy, but a grant exists (grant and policy set disagree)",
  rls_enabled_not_forced:
    "Row-level security enabled but not FORCED (the table owner is not subject to it)",
  anon_reachable: "Reachable without an account",
  anon_granted_but_no_policy_admits_it:
    "Granted to anon, but no policy admits anon — denied by row security, and the grant is latent",
  public_grant: "Granted to PUBLIC",
  view_bypasses_invoker_rls:
    "View is not security_invoker, so underlying policies run as the view owner",
  write_policy_without_with_check:
    "A policy governing a write path has no WITH CHECK expression",
  security_definer_without_pinned_search_path:
    "SECURITY DEFINER function, callable by a client role, with no search_path pinned",
};

export function renderInventoryMarkdown(inv: Inventory, meta: RunMeta): string {
  const L: string[] = [];
  const p = (s = "") => L.push(s);

  p(`# Control inventory — Arc21`);
  p();
  p(`Generated by Attest. Every row below is read from the PostgreSQL system catalogs of a`);
  p(`disposable local instance rebuilt from migrations. Nothing in this document is hand-written.`);
  p();
  p(`| | |`);
  p(`|---|---|`);
  p(`| Run | \`${meta.runId}\` |`);
  p(`| Started | ${meta.startedAt} |`);
  p(`| Instance | ${meta.instance} |`);
  p(`| Schema version | \`${meta.schemaVersion.migrationSetSha256}\` |`);
  p(`| Migrations | ${meta.schemaVersion.migrationCount} files |`);
  p(`| Source commit | \`${meta.schemaVersion.git.commit ?? "unknown"}\` on \`${meta.schemaVersion.git.branch ?? "?"}\`${meta.schemaVersion.git.dirty ? " (working tree dirty)" : ""} |`);
  if (meta.schemaVersion.git.uncommittedMigrations.length) {
    p(`| Migrations not in git | ${meta.schemaVersion.git.uncommittedMigrations.map((m) => `\`${m}\``).join(", ")} |`);
  }
  p(`| Read as | \`${meta.readAs.currentUser}\` (session user \`${meta.readAs.sessionUser}\`, bypasses RLS: ${yn(meta.readAs.bypassesRls)}) |`);
  p();
  p(`> The inventory is read with a privileged role on purpose: reading the catalogs is not a`);
  p(`> control test. No control test in this project runs on this connection — see the role`);
  p(`> scoping in \`src/db.ts\`.`);
  p();

  // --- summary -----------------------------------------------------------
  p(`## What is here`);
  p();
  p(`| | Count |`);
  p(`|---|---:|`);
  p(`| Resources in scope | ${inv.counts.resources} |`);
  p(`| (resource, control) pairs | ${inv.counts.controls} |`);
  for (const k of Object.keys(inv.counts).filter((k) => k.startsWith("control.")).sort()) {
    p(`| — ${k.replace("control.", "").replaceAll("_", " ")} | ${inv.counts[k]} |`);
  }
  p(`| Structural observations | ${inv.counts.observations} |`);
  p();

  // --- roles -------------------------------------------------------------
  p(`## Roles on the instance`);
  p();
  p(`A role with \`bypasses RLS\` or \`superuser\` set is not subject to any row policy. Any test`);
  p(`run on such a connection passes whether or not the policy works.`);
  p();
  p(`| Role | Superuser | Bypasses RLS | Can log in | Inherits | Member of |`);
  p(`|---|---|---|---|---|---|`);
  for (const r of inv.roles) {
    const mem = Array.isArray(r.member_of) ? (r.member_of as string[]) : [];
    p(`| \`${cell(r.role_name)}\` | ${yn(r.is_superuser === true)} | **${yn(r.bypasses_rls === true)}** | ${yn(r.can_login === true)} | ${yn(r.inherits === true)} | ${mem.length ? mem.map((m) => `\`${m}\``).join(", ") : "—"} |`);
  }
  p();

  // --- resources ---------------------------------------------------------
  p(`## Resources and their row-level security state`);
  p();
  p(`\`Enabled\` means policies are consulted for ordinary roles. \`Forced\` means they are also`);
  p(`consulted for the table's **owner**. A table that is enabled but not forced is unrestricted`);
  p(`to whoever owns it.`);
  p();
  p(`\`Reachable by\` lists only grantees that also hold USAGE on the containing schema — a grant`);
  p(`inside a schema nobody may enter is not reachable.`);
  p();
  p(`\`Refusing triggers\` lists triggers whose function can raise, which is how this system`);
  p(`refuses writes that the privilege system and the policies would otherwise allow — and the`);
  p(`only way to refuse \`TRUNCATE\`, which row-level security does not cover at all. The`);
  p(`classification is a **heuristic** on the function body; housekeeping triggers such as`);
  p(`\`set_updated_at\` are excluded by it. Whether a trigger actually refuses anything is settled`);
  p(`by executing a statement, not by reading its source.`);
  p();
  p(`| Resource | Kind | Owner | RLS enabled | RLS forced | Policies | Reachable by | Refusing triggers |`);
  p(`|---|---|---|---|---|---:|---|---|`);
  for (const r of inv.resources) {
    const reach = Object.entries(r.reachableBy)
      .map(([g, privs]) => `${g}: ${privs.join(", ")}`)
      .join("<br>") || "—";
    const isTable = r.kind === "table" || r.kind === "partitioned_table";
    p(
      `| \`${r.resource}\` | ${r.kind} | \`${r.owner}\` | ${isTable ? yn(r.rlsEnabled) : "n/a"} | ${isTable ? yn(r.rlsForced) : "n/a"} | ${r.policyCount} | ${reach} | ${r.writeGuards.length ? r.writeGuards.map((g) => `\`${g}\``).join("<br>") : "—"} |`,
    );
  }
  p();

  // --- column grants -----------------------------------------------------
  const withCols = inv.resources.filter((r) => Object.keys(r.columnReachableBy).length > 0);
  p(`## Column-level grants`);
  p();
  p(`Column grants do not appear in a table's privileges and are invisible to any check that`);
  p(`looks only at the table.`);
  p();
  if (withCols.length === 0) {
    p(`None. No client-reachable role holds a column-level privilege on any resource in scope.`);
  } else {
    p(`| Resource | Grantee : column | Privileges |`);
    p(`|---|---|---|`);
    for (const r of withCols)
      for (const [key, privs] of Object.entries(r.columnReachableBy))
        p(`| \`${r.resource}\` | \`${cell(key)}\` | ${privs.join(", ")} |`);
  }
  p();

  // --- policies ----------------------------------------------------------
  p(`## Policies`);
  p();
  p(`\`USING\` decides which existing rows a command may see or touch. \`WITH CHECK\` decides which`);
  p(`rows it may write. They are different halves; a policy may carry one without the other.`);
  p();
  const policies = inv.controls.filter((c) => c.controlKind === "policy");
  p(`| Resource | Policy | Command | Kind | Roles | USING | WITH CHECK |`);
  p(`|---|---|---|---|---|---|---|`);
  for (const c of policies) {
    const d = c.detail as Record<string, unknown>;
    p(
      `| \`${c.resource}\` | \`${cell(d.policy_name)}\` | ${cell(d.command)} | ${cell(d.permissive)} | ${(d.roles as string[] ?? []).map((r) => `\`${r}\``).join(", ")} | ${code(d.using_expr)} | ${code(d.with_check_expr)} |`,
    );
  }
  p();

  // --- security definer --------------------------------------------------
  const definers = inv.controls.filter((c) => c.controlKind === "security_definer_function");
  const callable = definers.filter((c) => ((c.detail as any).executable_by as string[]).length > 0);
  p(`## SECURITY DEFINER functions`);
  p();
  p(`These execute with the privileges of their **owner**, not the caller. Inside one, the`);
  p(`caller's row policies no longer apply. ${definers.length} exist in the application schemas;`);
  p(`${callable.length} of them are executable by a role a client can present.`);
  p();
  p(`A function nobody can call is not an exposure. The table below lists only the callable ones;`);
  p(`the full set is in \`inventory.json\`.`);
  p();
  p(`| Function | Owner | search_path pinned | Executable by |`);
  p(`|---|---|---|---|`);
  for (const c of callable) {
    const d = c.detail as Record<string, unknown>;
    const cfg = (d.config as string[] | null) ?? [];
    const pinned = cfg.find((x) => x.toLowerCase().startsWith("search_path="));
    p(`| \`${cell(c.resource)}\` | \`${cell(d.owner)}\` | ${pinned ? `\`${cell(pinned)}\`` : "**no**"} | ${(d.executable_by as string[]).map((r) => `\`${r}\``).join(", ")} |`);
  }
  p();

  // --- realtime ----------------------------------------------------------
  p(`## Realtime exposure`);
  p();
  p(`Supabase Realtime has two mechanisms. **Postgres Changes** streams row changes for tables`);
  p(`added to the \`supabase_realtime\` publication. **Broadcast** carries named topics, authorized`);
  p(`by row policies on \`realtime.messages\` keyed on \`realtime.topic()\`. An empty publication`);
  p(`does not mean no realtime exposure — it means the exposure is on the Broadcast side.`);
  p();
  p(`| Publication | All tables | Tables |`);
  p(`|---|---|---|`);
  for (const pub of inv.publications) {
    const tables = (pub.tables as string[]) ?? [];
    p(`| \`${cell(pub.publication)}\` | ${yn(pub.all_tables === true)} | ${tables.length ? tables.map((t) => `\`${t}\``).join("<br>") : "*(none)*"} |`);
  }
  p();

  // --- anonymous reach ---------------------------------------------------
  const reach = inv.anonymousReach;
  const reachApp = reach.filter((r) => r.in_application_schema === true);
  const reachPlatform = reach.filter((r) => r.in_application_schema !== true);
  const platformRelations = reachPlatform.filter((r) => r.object_type === "relation");
  const platformFunctions = reachPlatform.filter((r) => r.object_type === "function");

  p(`## What a signed-out caller can reach`);
  p();
  p(`Every object on the instance on which \`anon\` or \`PUBLIC\` holds a privilege, and whose`);
  p(`schema they may also enter. This covers the whole instance, not only the application's`);
  p(`schemas: on a Supabase instance \`anon\` arrives already holding privileges on platform`);
  p(`tables that no application migration mentions, and an inventory scoped to the application`);
  p(`would report a clean anonymous surface while that was true.`);
  p();
  p(`\`pg_catalog\` and \`information_schema\` are excluded. Every PostgreSQL installation grants`);
  p(`PUBLIC read on the catalogs and EXECUTE on several hundred built-ins; they are true of every`);
  p(`database in the world and say nothing about this one.`);
  p();

  p(`### Application-owned — ${reachApp.length}`);
  p();
  p(`| Object | Type | Grantee | Privileges | RLS | Policies |`);
  p(`|---|---|---|---|---|---:|`);
  for (const r of reachApp) {
    p(`| \`${cell(r.resource)}\` | ${cell(r.object_type)} | \`${cell(r.grantee)}\` | ${cell(r.privileges)} | ${r.rls_enabled === null ? "n/a" : yn(r.rls_enabled === true)} | ${r.policy_count ?? "n/a"} |`);
  }
  p();

  p(`### Platform-owned — ${reachPlatform.length}`);
  p();
  p(`Supabase defaults. **These are not findings against Arc21.** They are not the author's code,`);
  p(`and this project raises no finding about a third party's system. They are here because the`);
  p(`honest answer to "what can a signed-out caller reach" includes them, and because anyone`);
  p(`reading this inventory to understand the instance needs to know the application's schemas`);
  p(`are not the whole surface.`);
  p();
  p(`Relations are listed in full — that is where data lives. Functions are summarised by schema;`);
  p(`the complete list, with full signatures, is in \`inventory.json\`.`);
  p();
  p(`| Platform relation | Grantee | Privileges | RLS | Policies |`);
  p(`|---|---|---|---|---:|`);
  for (const r of platformRelations) {
    p(`| \`${cell(r.resource)}\` | \`${cell(r.grantee)}\` | ${cell(r.privileges)} | ${yn(r.rls_enabled === true)} | ${r.policy_count ?? 0} |`);
  }
  p();

  // A platform relation with RLS off and write privileges granted to anon is
  // worth naming rather than leaving for the reader to spot in a table.
  const openPlatform = platformRelations.filter(
    (r) => r.rls_enabled !== true && /INSERT|UPDATE|DELETE|TRUNCATE/.test(String(r.privileges ?? "")),
  );
  if (openPlatform.length) {
    p(`Of those, ${openPlatform.length} carry write privileges for \`anon\` with row-level security`);
    p(`switched off:`);
    p();
    for (const r of openPlatform) p(`- \`${cell(r.resource)}\` — ${cell(r.privileges)}`);
    p();
    p(`Again: Supabase's defaults on a local development stack, not Arc21's code and not a finding`);
    p(`against it. Recorded because it is true of the instance the evidence was collected on.`);
    p();
  }

  const fnByschema = new Map<string, number>();
  for (const f of platformFunctions)
    fnByschema.set(String(f.schema_name), (fnByschema.get(String(f.schema_name)) ?? 0) + 1);
  const definerFns = platformFunctions.filter((f) => String(f.privileges ?? "").includes("SECURITY DEFINER"));
  p(`| Platform functions by schema | Count |`);
  p(`|---|---:|`);
  for (const [schema, n] of [...fnByschema.entries()].sort()) p(`| \`${schema}\` | ${n} |`);
  p();
  if (definerFns.length) {
    p(`${definerFns.length} of them ${definerFns.length === 1 ? "is" : "are"} SECURITY DEFINER and`);
    p(`therefore executes with its owner's privileges rather than the caller's:`);
    p();
    for (const f of definerFns) p(`- \`${cell(f.resource)}\` — reachable by \`${cell(f.grantee)}\``);
    p();
  }

  // --- default privileges ------------------------------------------------
  p(`## Default privileges`);
  p();
  p(`What a table created **tomorrow** will grant the moment it exists, before anyone writes a`);
  p(`policy for it.`);
  p();
  if (inv.defaultPrivileges.length === 0) {
    p(`None set for any client-reachable role. A new table grants nothing until a grant is written.`);
  } else {
    p(`| Schema | Owner role | Object type | Grantee | Privilege |`);
    p(`|---|---|---|---|---|`);
    for (const d of inv.defaultPrivileges)
      p(`| \`${cell(d.schema_name)}\` | \`${cell(d.owner_role)}\` | ${cell(d.object_type)} | \`${cell(d.grantee)}\` | ${cell(d.privilege)} |`);
  }
  p();

  // --- observations ------------------------------------------------------
  p(`## Structural observations`);
  p();
  p(`These are mechanical classifications of the surface above. **They are not findings and they`);
  p(`are not ranked.** Whether any of them matters is decided by the risk rubric (WP2) and`);
  p(`written up by hand (WP5). Listing them here pre-ranked would be this tool quietly writing`);
  p(`both.`);
  p();
  const byKind = new Map<Observation["kind"], Observation[]>();
  for (const o of inv.observations) byKind.set(o.kind, [...(byKind.get(o.kind) ?? []), o]);
  for (const [kind, list] of [...byKind.entries()].sort((a, x) => a[0].localeCompare(x[0]))) {
    p(`### ${OBSERVATION_HEADINGS[kind]} — ${list.length}`);
    p();
    for (const o of list) p(`- \`${o.resource}\` — ${o.detail}`);
    p();
  }

  // --- declared intent ---------------------------------------------------
  p(`## Appendix: declared intent`);
  p();
  p(`The author's \`COMMENT\` on each resource. This is a **claim about** the control, recorded`);
  p(`beside the measurement so the two can be compared. It is not evidence and no test result`);
  p(`depends on it.`);
  p();
  for (const r of inv.resources.filter((r) => r.declaredIntent)) {
    p(`- \`${r.resource}\` — ${cell(r.declaredIntent)}`);
  }
  p();

  return L.join("\n");
}
